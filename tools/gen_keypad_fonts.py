#!/usr/bin/env python3
"""Generate the ScreenPad bitmap fonts, Font Awesome icon atlas, and web assets.

Inputs (not committed; download the upstream releases):
  - Nunito variable TTF (Google Fonts, OFL)
  - Font Awesome Free desktop OTF + metadata/icons.json (CC BY 4.0 / OFL)
  - Font Awesome Free solid WOFF2 (for the web picker)

Outputs (committed):
  - headers/display/fonts/KeypadFontNunito{28,20,16}.h
  - headers/display/fonts/FontAwesomeSolid40.h
  - www/js/core/fontawesome-solid.js
  - www/fonts/fontawesome.css (font embedded as a data URI)

The generated files are deterministic for a given font version. This script is
not part of the firmware build; run it only when updating the fonts/icons.
"""

import argparse
import json
import math
import shutil
import tempfile
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent

GLYPH_FIRST = 32
GLYPH_LAST = 126
GLYPH_COUNT = GLYPH_LAST - GLYPH_FIRST + 1

ICON_SIZE = 40
ICON_BITS = 4
ICON_ROW_BYTES = (ICON_SIZE * ICON_BITS + 7) // 8
ICON_BYTES = ICON_ROW_BYTES * ICON_SIZE


def hex_bytes(data: bytes, per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        lines.append("  " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def write_font_header(path: Path, name: str, size: int, font: ImageFont.FreeTypeFont):
    ascent, descent = font.getmetrics()
    line_height = ascent + descent
    glyphs = []
    alpha = bytearray()
    for code in range(GLYPH_FIRST, GLYPH_LAST + 1):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        # Draw on a padded canvas with the baseline at `ascent`; crop to the
        # ink and record its offset from the pen/line origin.
        pad = 8
        canvas = Image.new("L", (max(advance, 1) + 2 * pad, line_height + 2 * pad), 0)
        draw = ImageDraw.Draw(canvas)
        draw.text((pad, ascent + pad), ch, font=font, fill=255, anchor="ls")
        bbox = canvas.getbbox()
        if bbox is None:
            glyphs.append((len(alpha), 0, 0, 0, 0, advance))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        crop = canvas.crop(bbox)
        alpha.extend(crop.tobytes())
        glyphs.append((len(alpha) - w * h, x0 - pad, y0 - pad, w, h, advance))

    out = [
        "// Generated by tools/gen_keypad_fonts.py. Do not edit.",
        f"// Nunito {name} at {size}px from the SIL OFL Nunito project.",
        "#ifndef _KEYPAD_FONT_" + name.upper() + "_H_",
        "#define _KEYPAD_FONT_" + name.upper() + "_H_",
        "",
        '#include "display/KeypadFont.h"',
        "",
        f"static const uint8_t KeypadFont{name}Alpha[] = {{",
        hex_bytes(bytes(alpha)),
        "};",
        "",
        f"static const KeypadGlyph KeypadFont{name}Glyphs[{GLYPH_COUNT}] = {{",
    ]
    for offset, xoff, yoff, w, h, advance in glyphs:
        out.append(f"  {{ {offset}, {xoff}, {yoff}, {w}, {h}, {advance} }},")
    out += [
        "};",
        "",
        f"static const KeypadFont KeypadFont{name} = {{",
        f"  {line_height}, KeypadFont{name}Glyphs, KeypadFont{name}Alpha",
        "};",
        "",
        "#endif",
        "",
    ]
    path.write_text("\n".join(out))
    print(f"wrote {path} ({len(alpha)} alpha bytes, {len(glyphs)} glyphs)")


def render_icon(font: ImageFont.FreeTypeFont, codepoint: int) -> bytes:
    canvas = Image.new("L", (ICON_SIZE * 2, ICON_SIZE * 2), 0)
    draw = ImageDraw.Draw(canvas)
    draw.text((ICON_SIZE, ICON_SIZE), chr(codepoint), font=font, fill=255, anchor="mm")
    bbox = canvas.getbbox()
    if bbox is None:
        return bytes(ICON_BYTES)
    ink = canvas.crop(bbox)
    # Keep a little breathing room and scale oversized glyphs down to fit.
    target = ICON_SIZE - 4
    scale = min(target / ink.width, target / ink.height, 1.0)
    if scale < 1.0:
        ink = ink.resize((max(1, int(ink.width * scale)), max(1, int(ink.height * scale))),
                         Image.LANCZOS)
    out = Image.new("L", (ICON_SIZE, ICON_SIZE), 0)
    out.paste(ink, ((ICON_SIZE - ink.width) // 2, (ICON_SIZE - ink.height) // 2))
    # Quantize into a 4-bit alpha mask (high nibble first).
    packed = bytearray(ICON_BYTES)
    px = out.load()
    for y in range(ICON_SIZE):
        for x in range(ICON_SIZE):
            a4 = (px[x, y] * 15 + 127) // 255
            if a4:
                idx = y * ICON_ROW_BYTES + (x >> 1)
                if x & 1:
                    packed[idx] |= a4
                else:
                    packed[idx] |= a4 << 4
    return bytes(packed)


def write_icon_header(path: Path, entries):
    mask = bytearray()
    table = []
    # The firmware does a binary search by codepoint.
    for cp, _name, _terms in sorted(entries, key=lambda item: item[0]):
        table.append((cp, len(mask)))
        mask.extend(render_icon(ICON_FONT, cp))
    out = [
        "// Generated by tools/gen_keypad_fonts.py. Do not edit.",
        "// Font Awesome Free 6.7.2 solid icons (CC BY 4.0, font SIL OFL).",
        "#ifndef _FONTAWESOME_SOLID48_H_",
        "#define _FONTAWESOME_SOLID48_H_",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONTAWESOME_ICON_SIZE {ICON_SIZE}",
        f"#define FONTAWESOME_ICON_BITS {ICON_BITS}",
        f"#define FONTAWESOME_ICON_ROW_BYTES {ICON_ROW_BYTES}",
        f"#define FONTAWESOME_ICON_BYTES {ICON_BYTES}",
        "",
        "struct KeypadIcon {",
        "  uint32_t codepoint;",
        "  uint32_t offset;",
        "};",
        "",
        "static const uint8_t FontAwesomeSolidMask[] = {",
        hex_bytes(bytes(mask)),
        "};",
        "",
        "static const KeypadIcon FontAwesomeSolidIcons[] = {",
    ]
    for cp, offset in table:
        out.append(f"  {{ 0x{cp:04x}u, {offset}u }},")
    out += [
        "};",
        "",
        f"#define FONTAWESOME_SOLID_COUNT {len(table)}",
        "",
        "#endif",
        "",
    ]
    path.write_text("\n".join(out))
    print(f"wrote {path} ({len(table)} icons, {len(mask)} mask bytes)")


def write_web_manifest(path: Path, entries):
    rows = []
    for cp, name, terms in entries:
        label = name.replace("-", " ").title()
        search = " ".join(terms).lower()
        rows.append(f'  ["{label}", 0x{cp:04x}, {json.dumps(search)}],')
    path.write_text(
        "// Generated by tools/gen_keypad_fonts.py. Do not edit.\n"
        "// Font Awesome Free 6.7.2 solid icons (CC BY 4.0).\n"
        "const FONTAWESOME_SOLID = [\n" + "\n".join(rows) + "\n];\n"
    )
    print(f"wrote {path} ({len(entries)} icons)")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--nunito", required=True, help="Nunito variable TTF")
    parser.add_argument("--fa-otf", required=True, help="Font Awesome Free solid OTF")
    parser.add_argument("--fa-metadata", required=True, help="Font Awesome icons.json")
    parser.add_argument("--fa-woff2", required=True, help="Font Awesome solid WOFF2")
    parser.add_argument("--out", default=str(ROOT))
    args = parser.parse_args()

    out = Path(args.out)
    fonts_dir = out / "headers" / "display" / "fonts"
    web_dir = out / "www"
    fonts_dir.mkdir(parents=True, exist_ok=True)
    (web_dir / "fonts").mkdir(parents=True, exist_ok=True)

    global ICON_FONT
    ICON_FONT = ImageFont.truetype(args.fa_otf, ICON_SIZE)

    # Nunito 700 (Bold) static instance from the variable font.
    variable = TTFont(args.nunito)
    static = instantiateVariableFont(variable, {"wght": 700})
    static_path = Path(tempfile.gettempdir()) / "mp2040-nunito-700.ttf"
    static.save(static_path)

    for name, size in (("Nunito28", 28), ("Nunito20", 20), ("Nunito16", 16)):
        font = ImageFont.truetype(str(static_path), size)
        write_font_header(fonts_dir / f"KeypadFont{name}.h", name, size, font)

    metadata = json.load(open(args.fa_metadata, encoding="utf-8"))
    entries = []
    for name, data in metadata.items():
        if "solid" not in data.get("styles", []):
            continue
        cp = int(data["unicode"], 16)
        terms = data.get("search", {}).get("terms", [])
        entries.append((cp, name, terms[:10]))
    entries.sort(key=lambda item: item[1].lower())

    write_icon_header(fonts_dir / "FontAwesomeSolid40.h", entries)
    write_web_manifest(web_dir / "js" / "core" / "fontawesome-solid.js", entries)
    # Bundle the font inside a ScreenPad-only stylesheet as a data URI. This
    # avoids a separate font request and any cache/URL/MIME issue.
    import base64
    font_b64 = base64.b64encode(Path(args.fa_woff2).read_bytes()).decode("ascii")
    font_css = (
        "/* Font Awesome Free 6.7.2 solid, SIL OFL. Generated by tools/gen_keypad_fonts.py. */\n"
        "@font-face {\n"
        "  font-family: 'Font Awesome 6 Free';\n"
        "  font-style: normal;\n"
        "  font-weight: 900;\n"
        "  font-display: block;\n"
        f"  src: url(data:font/woff2;base64,{font_b64}) format('woff2');\n"
        "}\n"
    )
    font_css_path = web_dir / "fonts" / "fontawesome.css"
    font_css_path.write_text(font_css)
    print(f"wrote {font_css_path} (embedded font)")


if __name__ == "__main__":
    main()
